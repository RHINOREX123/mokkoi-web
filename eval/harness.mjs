#!/usr/bin/env node
// eval/harness.mjs — orchestrates Mokkoi quality scoring.
//
// Three modes:
//   --mode=snapshot   Score every screen in eval/snapshot-2026-04-28.json
//                     (the 303 production screens captured Day 1). No API
//                     calls. Free.
//   --mode=fresh      Generate 30 fresh apps via /api/generate-flow logic,
//                     score them. Requires ANTHROPIC_API_KEY in env.
//   --mode=judge      Add Anthropic AI-judge scores to an existing results
//                     file. Requires ANTHROPIC_API_KEY.
//
// Output:
//   eval/<mode>-<date>.json    machine-readable per-screen + aggregate
//   eval/<mode>-<date>.md      human-readable summary
//
// Re-runnable: every run produces a new dated file. Day 3-4 prompt
// iterations re-run --mode=fresh and diff against today's baseline.

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { TEST_SET, ARCHETYPES } from './test-set.mjs'
import { scoreScreen, aggregate, TARGETED_MACROS, MACRO_TYPES } from './scoring.mjs'
import { isKnownIcon } from './load-icon-validator.mjs'

// ─── Inline .env loader ────────────────────────────────────────────────
// Node's `--env-file` flag does NOT override variables already set in the
// parent process — even when the existing value is an empty string. Some
// shells / tool harnesses leak `ANTHROPIC_API_KEY=""` into the env, which
// silently blocks the harness from picking up the real key in `.env`. We
// load `.env` explicitly here and OVERRIDE existing values, so the harness
// works reliably regardless of how it's launched.
;(function loadDotEnv() {
  const envPath = new URL('../.env', import.meta.url)
  if (!existsSync(envPath)) return
  const text = readFileSync(envPath, 'utf8')
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq < 1) continue
    const key = line.slice(0, eq).trim()
    let val = line.slice(eq + 1).trim()
    // Strip surrounding quotes if present
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1)
    }
    // Override even if already set — fixes the empty-shell-export case.
    process.env[key] = val
  }
})()

const args = Object.fromEntries(
  process.argv.slice(2).map(a => {
    const [k, v] = a.replace(/^--/, '').split('=')
    return [k, v ?? true]
  }),
)

const MODE = args.mode || 'snapshot'
const TODAY = new Date().toISOString().slice(0, 10) // YYYY-MM-DD

function log(msg, ...rest) {
  console.log(`[${new Date().toISOString().slice(11, 19)}] ${msg}`, ...rest)
}

// ─── Snapshot mode ─────────────────────────────────────────────────────
async function runSnapshot() {
  const path = new URL('./snapshot-2026-04-28.json', import.meta.url)
  if (!existsSync(path)) {
    console.error('Missing eval/snapshot-2026-04-28.json. Run Day 1 first.')
    process.exit(1)
  }
  log(`Loading snapshot from ${path}`)
  const snap = JSON.parse(readFileSync(path, 'utf8'))
  log(`Loaded ${snap.total_screens} screens`)

  const screens = snap.screens.filter(s => s.tree && s.total_nodes >= 30)
  log(`Filtered to ${screens.length} real (>=30 node) screens`)

  const scored = []
  for (const s of screens) {
    const score = scoreScreen(s.tree, isKnownIcon)
    scored.push({
      id: s.id,
      project_id: s.project_id,
      name: s.name,
      ...score,
    })
  }

  const agg = aggregate(scored)
  return {
    mode: 'snapshot',
    captured_at: new Date().toISOString(),
    source: 'eval/snapshot-2026-04-28.json',
    note: '303 production screens generated by real users. Used as the natural baseline before any prompt rewrite.',
    aggregate: agg,
    per_archetype: null, // snapshot doesn't have archetype labels
    screens: scored,
  }
}

// ─── Fresh mode ────────────────────────────────────────────────────────
async function runFresh() {
  const apiKey = process.env.ANTHROPIC_API_KEY
  if (!apiKey) {
    console.error('Set ANTHROPIC_API_KEY in env to run fresh mode.')
    console.error('Tip: cp .env.example .env, then fill in ANTHROPIC_API_KEY.')
    process.exit(1)
  }

  // Load Mokkoi's prompts dynamically from the API source.
  const { plannerSystem, appGenerationSystem, buildGenPrompt } = await loadMokkoiPrompts()

  const partialPath = new URL(`./fresh-${TODAY}.partial.json`, import.meta.url)
  let partial = []
  if (existsSync(partialPath)) {
    partial = JSON.parse(readFileSync(partialPath, 'utf8'))
    log(`Resuming with ${partial.length} prompts already complete`)
  }
  const completed = new Set(partial.map(p => p.test_id))

  const allResults = [...partial]
  let remaining = TEST_SET.filter(t => !completed.has(t.id))
  if (args.limit) {
    remaining = remaining.slice(0, Number(args.limit))
    log(`--limit=${args.limit} — running ${remaining.length} prompts (smoke test)`)
  }

  for (let i = 0; i < remaining.length; i++) {
    const t = remaining[i]
    log(`(${i + 1}/${remaining.length}) ${t.id} [${t.archetype}] "${t.prompt.slice(0, 50)}..."`)
    const result = await generateAndScore(t, apiKey, plannerSystem, appGenerationSystem, buildGenPrompt)
    allResults.push(result)
    // Save partial after each prompt — crash recovery. Inter-app pacing is
    // handled by the rolling token-budget throttle in callAnthropic().
    writeFileSync(partialPath, JSON.stringify(allResults, null, 2))
  }

  // Aggregate per-archetype
  const perArchetype = {}
  for (const arch of ARCHETYPES) {
    const archResults = allResults.filter(r => r.archetype === arch && r.success)
    const allScreens = archResults.flatMap(r => r.screen_scores)
    perArchetype[arch] = {
      apps: archResults.length,
      screens: allScreens.length,
      ...aggregate(allScreens),
    }
  }

  const allScreens = allResults.filter(r => r.success).flatMap(r => r.screen_scores)
  return {
    mode: 'fresh',
    captured_at: new Date().toISOString(),
    test_set_size: TEST_SET.length,
    apps_generated: allResults.filter(r => r.success).length,
    apps_failed: allResults.filter(r => !r.success).length,
    aggregate: aggregate(allScreens),
    per_archetype: perArchetype,
    apps: allResults,
  }
}

async function generateAndScore(test, apiKey, plannerSystem, appGenSystem, buildGenPrompt) {
  let lastErr
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const t0 = Date.now()
      // Phase 1: planner
      const plan = await callAnthropic({
        apiKey,
        model: 'claude-haiku-4-5-20251001',
        max_tokens: 2000,
        system: plannerSystem,
        messages: [{ role: 'user', content: test.prompt }],
      })
      const planText = stripCodeFences(plan?.content?.[0]?.text || '')
      let planObj
      try { planObj = JSON.parse(planText) } catch { planObj = repairJSON(planText) }
      if (!planObj?.screens || !Array.isArray(planObj.screens) || planObj.screens.length < 2) {
        throw new Error('plan returned no screens')
      }

      // Phase 2: generation
      const genPrompt = buildGenPrompt(test.prompt, planObj)
      const gen = await callAnthropic({
        apiKey,
        model: 'claude-haiku-4-5-20251001', // free-tier model — same one production uses for free users
        max_tokens: 10000,
        system: appGenSystem,
        messages: [{ role: 'user', content: genPrompt }],
      })
      const genText = stripCodeFences(gen?.content?.[0]?.text || '')
      const screens = parseScreenArray(genText)
      if (!screens || !Array.isArray(screens) || screens.length === 0) {
        // Dump raw response for diagnosis
        const dbgPath = new URL(`./debug-${test.id}-attempt${attempt}.txt`, import.meta.url)
        writeFileSync(dbgPath, `stop_reason=${gen?.stop_reason}\nusage=${JSON.stringify(gen?.usage)}\n--- raw text ---\n${genText}`)
        throw new Error(`generation returned no screens (stop=${gen?.stop_reason}, len=${genText.length})`)
      }

      // Score every generated screen
      const screenScores = screens.map(s => ({
        id: s.id,
        name: s.name,
        ...scoreScreen(s.tree, isKnownIcon),
      }))
      const elapsedMs = Date.now() - t0
      log(`  ✓ ${screens.length} screens in ${(elapsedMs/1000).toFixed(1)}s, density mean=${(screenScores.reduce((a,s)=>a+s.macro_density,0)/screenScores.length).toFixed(3)}`)
      return {
        test_id: test.id,
        archetype: test.archetype,
        prompt: test.prompt,
        success: true,
        elapsed_ms: elapsedMs,
        attempt,
        plan: { appName: planObj.appName, screen_count: planObj.screens.length },
        screen_scores: screenScores,
      }
    } catch (err) {
      lastErr = err
      log(`  ✗ attempt ${attempt}/3 failed: ${err.message}`)
      if (attempt < 3) await new Promise(r => setTimeout(r, 2000 * attempt))
    }
  }
  return {
    test_id: test.id,
    archetype: test.archetype,
    prompt: test.prompt,
    success: false,
    error: lastErr?.message ?? 'unknown',
    screen_scores: [],
  }
}

// ─── Rolling token-budget throttle ─────────────────────────────────────
// Dev Anthropic key is capped at 10,000 OUTPUT tokens / minute. Anthropic
// charges max_tokens against the rate budget at request time, so we must
// pace requests by their REQUESTED ceiling, not their actual usage.
const TOKEN_BUDGET = 10_000
const WINDOW_MS = 60_000
const RECENT = []  // [{t, tokens}]
async function reserveTokens(maxTokens) {
  while (true) {
    const now = Date.now()
    while (RECENT.length && now - RECENT[0].t > WINDOW_MS) RECENT.shift()
    const used = RECENT.reduce((a, r) => a + r.tokens, 0)
    if (used + maxTokens <= TOKEN_BUDGET) {
      RECENT.push({ t: now, tokens: maxTokens })
      return
    }
    // Sleep until the oldest entry rolls off, plus 1s buffer
    const wait = (RECENT[0].t + WINDOW_MS) - now + 1000
    log(`  … rate-budget: ${used}/${TOKEN_BUDGET} reserved, waiting ${(wait/1000).toFixed(0)}s`)
    await new Promise(r => setTimeout(r, Math.max(wait, 1000)))
  }
}

async function callAnthropic({ apiKey, model, max_tokens, system, messages }) {
  await reserveTokens(max_tokens)
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model, max_tokens,
      system: [{ type: 'text', text: system, cache_control: { type: 'ephemeral' } }],
      messages,
    }),
  })
  if (!res.ok) {
    const body = await res.text()
    throw new Error(`anthropic ${res.status}: ${body.slice(0, 200)}`)
  }
  return res.json()
}

// ─── Lightweight stripCodeFences / repairJSON / parseScreenArray ───────
// Mirrors api/generate-flow.ts logic — same input handling so the harness
// catches the same kinds of failures the production endpoint does.
function stripCodeFences(text) {
  return text.replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '').trim()
}
function repairJSON(text) {
  // Try common fixes: trailing comma, missing closing brackets
  let t = text.trim()
  if (!t.endsWith('}') && !t.endsWith(']')) {
    const opens = (t.match(/[{\[]/g) || []).length
    const closes = (t.match(/[}\]]/g) || []).length
    const diff = opens - closes
    if (diff > 0) t += '}'.repeat(diff)
  }
  return JSON.parse(t)
}
function parseScreenArray(text) {
  let t = text
  // Strip leading "screens:" or similar
  const arrStart = t.indexOf('[')
  if (arrStart > 0) t = t.slice(arrStart)
  try { return JSON.parse(t) } catch {}
  try { return repairJSON(t) } catch { return null }
}

// ─── Loader for Mokkoi prompts (read source files, no TypeScript compile) ──
async function loadMokkoiPrompts() {
  // Inline the planner system prompt builder — read api/_lib/design-system.ts
  // and pull APP_PLANNER_SYSTEM_PROMPT + TEMPLATE_PRIORS via dynamic require.
  // Easiest: re-export them as a JS-readable module. For now, hardcode by
  // reading the .ts file and eval'ing the constants.
  const { default: extracted } = await import('./_load-prompts.mjs')
  return extracted
}

// ─── Main ──────────────────────────────────────────────────────────────
async function main() {
  log(`Mokkoi eval harness — mode=${MODE}, date=${TODAY}`)

  let result
  if (MODE === 'snapshot') {
    result = await runSnapshot()
  } else if (MODE === 'fresh') {
    result = await runFresh()
  } else if (MODE === 'judge') {
    console.error('judge mode not implemented in initial harness; will add when fresh-mode results are available')
    process.exit(1)
  } else {
    console.error(`Unknown mode: ${MODE}. Use --mode=snapshot|fresh|judge`)
    process.exit(1)
  }

  const jsonPath = new URL(`./${MODE}-${TODAY}.json`, import.meta.url)
  writeFileSync(jsonPath, JSON.stringify(result, null, 2))
  log(`Wrote ${jsonPath.pathname}`)

  const mdPath = new URL(`./${MODE}-${TODAY}.md`, import.meta.url)
  writeFileSync(mdPath, renderMarkdown(result))
  log(`Wrote ${mdPath.pathname}`)

  // Headline summary
  const a = result.aggregate
  console.log('')
  console.log('═══ HEADLINE NUMBERS ═══')
  console.log(`Mode: ${result.mode}, screens scored: ${a.count}`)
  if (a.count === 0) {
    console.log('No screens scored — every app failed. See partial JSON for errors.')
    return
  }
  console.log(`Macro density (mean):   ${(a.macro_density_mean * 100).toFixed(2)}%`)
  console.log(`Macro presence:         ${(a.macro_presence_rate * 100).toFixed(1)}%`)
  for (const m of TARGETED_MACROS) {
    console.log(`${(m + ' adoption:').padEnd(24)}${(a.targeted_adoption[m] * 100).toFixed(1)}%`)
  }
  console.log(`Icon validity (mean):   ${(a.icon_validity_mean * 100).toFixed(2)}%`)
  console.log(`Content realism (mean): ${(a.content_realism_mean * 100).toFixed(2)}%`)
  console.log(`Tree size in range:     ${(a.size_in_range_rate * 100).toFixed(1)}%  (too_small=${(a.size_too_small_rate * 100).toFixed(1)}%, too_large=${(a.size_too_large_rate * 100).toFixed(1)}%)`)
  console.log(`Mean nodes:             ${a.nodes_mean.toFixed(0)}  (median=${a.nodes_median})`)
}

function renderMarkdown(result) {
  const a = result.aggregate
  const lines = []
  lines.push(`# Mokkoi eval — ${result.mode} mode (${result.captured_at.slice(0, 10)})`)
  lines.push('')
  if (result.note) lines.push(`> ${result.note}`)
  lines.push('')
  lines.push('## Headline numbers')
  lines.push('')
  lines.push('| Metric | Value |')
  lines.push('|--------|------:|')
  lines.push(`| Screens scored | ${a.count} |`)
  if (a.count === 0) {
    lines.push('')
    lines.push('_No screens scored — every app failed. See partial JSON for errors._')
    lines.push('')
    return lines.join('\n') + '\n'
  }
  lines.push(`| Macro density (mean) | **${(a.macro_density_mean * 100).toFixed(2)}%** |`)
  lines.push(`| Macro presence (≥1 macro per screen) | ${(a.macro_presence_rate * 100).toFixed(1)}% |`)
  for (const m of TARGETED_MACROS) {
    lines.push(`| ${m} adoption | ${(a.targeted_adoption[m] * 100).toFixed(1)}% |`)
  }
  lines.push(`| Icon validity | ${(a.icon_validity_mean * 100).toFixed(2)}% |`)
  lines.push(`| Content realism | ${(a.content_realism_mean * 100).toFixed(2)}% |`)
  lines.push(`| Tree size in 50-180 range | ${(a.size_in_range_rate * 100).toFixed(1)}% |`)
  lines.push(`| Tree too small (<50) | ${(a.size_too_small_rate * 100).toFixed(1)}% |`)
  lines.push(`| Tree too large (>180) | ${(a.size_too_large_rate * 100).toFixed(1)}% |`)
  lines.push(`| Mean nodes per screen | ${a.nodes_mean.toFixed(0)} |`)
  lines.push(`| Median nodes per screen | ${a.nodes_median} |`)
  lines.push('')
  if (result.per_archetype) {
    lines.push('## Per-archetype breakdown')
    lines.push('')
    lines.push('| Archetype | Apps | Screens | Density | Presence | BottomNav | ListRow | ChipSelector | Realism |')
    lines.push('|-----------|-----:|--------:|--------:|---------:|----------:|--------:|-------------:|--------:|')
    for (const [arch, data] of Object.entries(result.per_archetype)) {
      if (data.count === 0) continue
      lines.push(`| ${arch} | ${data.apps} | ${data.screens} | ${(data.macro_density_mean*100).toFixed(1)}% | ${(data.macro_presence_rate*100).toFixed(0)}% | ${(data.targeted_adoption.BottomNav*100).toFixed(0)}% | ${(data.targeted_adoption.ListRow*100).toFixed(0)}% | ${(data.targeted_adoption.ChipSelector*100).toFixed(0)}% | ${(data.content_realism_mean*100).toFixed(0)}% |`)
    }
    lines.push('')
  }
  lines.push('')
  lines.push(`Generated by \`eval/harness.mjs --mode=${result.mode}\` at ${result.captured_at}.`)
  return lines.join('\n') + '\n'
}

main().catch(err => {
  console.error('Harness failed:', err)
  process.exit(1)
})
